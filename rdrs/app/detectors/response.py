"""Incident response actions (FR-8, FR-9): alerts, incidents, quarantine.

Simulation mode is on by default: if "kill process" were ever enabled,
this module only logs what it *would* do — it never terminates anything.
Evidence quarantine always COPIES files, never moves or deletes originals.
"""
from __future__ import annotations

import json
import shutil
from datetime import datetime
from pathlib import Path
from typing import List

from app.core.logging_setup import get_logger
from app.core.models import ThreatScore
from app.database.db import AlertRecord, IncidentRecord, get_session

audit_log = get_logger("audit")
alert_log = get_logger("alerts")


def quarantine_files(paths: List[str], quarantine_dir: str) -> List[str]:
    """Copy affected files into the quarantine folder. Originals are untouched."""
    dest_dir = Path(quarantine_dir)
    dest_dir.mkdir(parents=True, exist_ok=True)
    copied = []
    timestamp = datetime.utcnow().strftime("%Y%m%dT%H%M%S")

    for src in paths:
        src_path = Path(src)
        if not src_path.exists() or not src_path.is_file():
            continue
        dest_name = f"{timestamp}_{src_path.name}"
        dest_path = dest_dir / dest_name
        try:
            shutil.copy2(src_path, dest_path)
            copied.append(str(dest_path))
        except OSError as exc:
            audit_log.warning(f"Failed to quarantine {src_path}: {exc}")
    return copied


def simulate_process_action(action: str, process_name: str | None, simulation_mode: bool) -> None:
    """Log what a response action would do. Never actually terminate a process."""
    target = process_name or "unknown process"
    if simulation_mode:
        audit_log.info(f"[SIMULATION] Would perform '{action}' on {target} — no action taken")
    else:
        # Intentionally not implemented: RDRS never kills processes, even
        # outside simulation mode, per the responsible-use rules.
        audit_log.warning(
            f"Action '{action}' on {target} requested but process termination "
            "is disabled by policy — logging only."
        )


def handle_score(score: ThreatScore, quarantine_dir: str, simulation_mode: bool) -> int | None:
    """Given a threat score, log an alert and, on Critical, open an incident.

    Returns the new incident id, or None if no incident was created.
    """
    session = get_session()
    try:
        alert_msg = (
            f"Threat score {score.score} ({score.level.value}) — "
            f"signals: {score.signals.model_dump()}"
        )
        session.add(AlertRecord(level=score.level.value, score=score.score, message=alert_msg))
        session.commit()
        alert_log.info(alert_msg)

        if score.level.value != "Critical":
            return None

        quarantined = quarantine_files(score.affected_files, quarantine_dir)
        simulate_process_action("terminate", score.suspect_process, simulation_mode)

        incident = IncidentRecord(
            score=score.score,
            level=score.level.value,
            affected_files_json=json.dumps(score.affected_files),
            suspect_process=score.suspect_process,
            quarantined_files_json=json.dumps(quarantined),
            notes="Auto-generated by detection engine.",
        )
        session.add(incident)
        session.commit()
        session.refresh(incident)

        audit_log.info(
            f"Incident #{incident.id} created — score={score.score}, "
            f"files={len(score.affected_files)}, quarantined={len(quarantined)}"
        )
        return incident.id
    finally:
        session.close()
